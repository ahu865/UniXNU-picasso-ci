#!/usr/bin/env python3
"""Generate the embedded WCN3990 WLAN firmware array for the NativeWlan probe.

The repository never carries vendor blobs. This script turns the file staged in
WLAN_FW_DIR (default /tmp/picasso-wlan-fw) into one C translation unit that
defines the weak-import symbols WlanProbe.cpp consumes:

    native_wlan_firmware[]       wlanmdsp.mbn, the WCN3990 WLAN firmware image
    native_wlan_firmware_size

The image comes from the phone's own modem partition (NON-HLOS.bin, FAT16,
/image/wlanmdsp.mbn); it is the MBN the ICNSS/WLFW flow downloads into the MSA
region. A missing file produces a zero-size array, so the build stays
deterministic and probe stage 3 reports "no firmware staged" instead of
failing to link.
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = Path(os.environ.get('WLAN_FW_OUT') or (ROOT / 'build/native-wlan'))
FW_DIR = Path(os.environ.get('WLAN_FW_DIR') or '/tmp/picasso-wlan-fw')

FILES = {'firmware': 'wlanmdsp.mbn'}


def emit(name, data, lines):
    symbol = f'native_wlan_{name}'
    lines.append(f'const uint8_t {symbol}[] = {{')
    if data:
        for start in range(0, len(data), 16):
            lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[start:start + 16]) + ',')
    else:
        # A zero-length array is not valid C; one dummy byte with a zero size keeps the symbol defined.
        lines.append('    0x00,')
    lines.append('};')
    lines.append(f'const uint32_t {symbol}_size = {len(data)}u;')


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by scripts/build-wlan-picasso-firmware.py; no vendor blob is committed. */',
             '#include <stdint.h>', '']
    for name, filename in FILES.items():
        path = FW_DIR / filename
        data = path.read_bytes() if path.is_file() else b''
        emit(name, data, lines)
        print(f'wlan fw {name:8s} {filename:16s} {len(data)} bytes'
              + ('' if data else ' (missing: stage 3 will report no firmware staged)'))
    target = OUT_DIR / 'wlan_embedded_firmware.c'
    target.write_text('\n'.join(lines) + '\n')
    print(f'wrote {target}')


if __name__ == '__main__':
    main()
